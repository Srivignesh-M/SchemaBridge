/* ============================================================
   1. BASIC TABLE + ORACLE DATA TYPES
   ============================================================ */

CREATE TABLE EMPLOYEE (
    EMP_ID          NUMBER(10) PRIMARY KEY,
    EMP_NAME        VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(150),
    SALARY          NUMBER(12,2),
    BONUS           NUMBER,
    IS_ACTIVE       CHAR(1) DEFAULT 'Y',
    JOIN_DATE       DATE,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP,
    DESCRIPTION     CLOB,
    PROFILE_DATA    BLOB
);


