/* ============================================================
   42. MERGE / UPSERT
   ============================================================ */

MERGE INTO DEPARTMENT d
USING (
    SELECT 1 AS DEPT_ID,
           'Engineering Updated' AS DEPT_NAME,
           'Chennai' AS LOCATION
    FROM DUAL
) src
ON (d.DEPT_ID = src.DEPT_ID)

WHEN MATCHED THEN
    UPDATE SET
        d.DEPT_NAME = src.DEPT_NAME,
        d.LOCATION = src.LOCATION

WHEN NOT MATCHED THEN
    INSERT
        (DEPT_ID, DEPT_NAME, LOCATION)
    VALUES
        (src.DEPT_ID, src.DEPT_NAME, src.LOCATION);


/* ============================================================
   43. MERGE WITH CONDITIONAL UPDATE
   ============================================================ */

MERGE INTO EMPLOYEE e
USING (
    SELECT 101 AS EMP_ID,
           75000 AS SALARY
    FROM DUAL
) src
ON (e.EMP_ID = src.EMP_ID)

WHEN MATCHED THEN
    UPDATE SET
        e.SALARY = src.SALARY

WHEN NOT MATCHED THEN
    INSERT
        (EMP_ID, EMP_NAME, SALARY)
    VALUES
        (src.EMP_ID, 'New Employee', src.SALARY);


